-- Lançamentos mensais do Opa por colaborador.
-- Nota exibida = encerrados + transferidos; iniciados permanecem como indicador.

create table if not exists public.opa_resultados_mensais (
  id bigint generated by default as identity primary key,
  filial_id bigint not null references public.filiais(id) on delete cascade,
  vendedor_id bigint not null references public.vendedores(id) on delete cascade,
  mes integer not null check (mes between 1 and 12),
  ano integer not null check (ano between 2000 and 2200),
  iniciados integer not null default 0 check (iniciados >= 0),
  encerrados integer not null default 0 check (encerrados >= 0),
  transferidos integer not null default 0 check (transferidos >= 0),
  atualizado_em timestamptz not null default now(),
  constraint opa_resultados_mensais_vendedor_mes_key unique (filial_id, vendedor_id, mes, ano)
);

create index if not exists opa_resultados_mensais_filial_periodo_idx
  on public.opa_resultados_mensais (filial_id, ano, mes);

alter table public.opa_resultados_mensais enable row level security;

drop policy if exists opa_resultados_mensais_public_read on public.opa_resultados_mensais;
create policy opa_resultados_mensais_public_read on public.opa_resultados_mensais
  for select to anon, authenticated using (true);

drop policy if exists opa_resultados_mensais_admin_write on public.opa_resultados_mensais;
create policy opa_resultados_mensais_admin_write on public.opa_resultados_mensais
  for all to authenticated
  using (private.admin_tem_acesso_filial(filial_id))
  with check (
    private.admin_tem_acesso_filial(filial_id)
    and exists (
      select 1
      from public.vendedores v
      where v.id = vendedor_id
        and v.filial_id = opa_resultados_mensais.filial_id
        and lower(coalesce(v.tipo, '')) = 'interno'
    )
  );

grant select on public.opa_resultados_mensais to anon, authenticated;
grant insert, update, delete on public.opa_resultados_mensais to authenticated;
grant usage, select on sequence public.opa_resultados_mensais_id_seq to authenticated;

comment on table public.opa_resultados_mensais is
  'Contagens mensais de atendimento Opa por vendedor interno; total exibido é encerrados + transferidos.';

notify pgrst, 'reload schema';
