-- Fila de revisão das importações IXC com vínculo incompleto. Quando contrato,
-- filial e data são confiáveis, a venda é gravada e conta imediatamente mesmo
-- sem vendedor/plano; apenas linhas sem dados essenciais ficam em pré-revisão.

begin;

-- Permite registrar a venda antes de classificar o plano.
alter table public.vendas alter column plano_id drop not null;

-- Inclui vendas sem plano definido na visão administrativa, para continuarem
-- entrando nas contagens da filial durante a revisão.
do $view$
declare
  v_definicao text;
begin
  if to_regclass('public.vendas_admin') is not null then
    select pg_get_viewdef('public.vendas_admin'::regclass, true) into v_definicao;
    if v_definicao ~* '\mjoin\s+(public\.)?planos\M' then
      v_definicao := regexp_replace(v_definicao, '\mjoin\s+(public\.)?planos\M', 'LEFT JOIN public.planos', 'gi');
    end if;
    if v_definicao ~* '\mjoin\s+(public\.)?vendedores\M' then
      v_definicao := regexp_replace(v_definicao, '\mjoin\s+(public\.)?vendedores\M', 'LEFT JOIN public.vendedores', 'gi');
    end if;
    -- A expressão acima também encontra a palavra JOIN dentro de LEFT JOIN;
    -- normaliza o resultado para não produzir a sintaxe inválida LEFT LEFT JOIN.
    v_definicao := regexp_replace(v_definicao, '\mLEFT\s+LEFT\s+JOIN\M', 'LEFT JOIN', 'gi');
    if v_definicao <> pg_get_viewdef('public.vendas_admin'::regclass, true) then
      execute 'create or replace view public.vendas_admin with (security_invoker = true) as ' || v_definicao;
    end if;
  end if;
end;
$view$;

create table if not exists public.vendas_importacao_revisao_ixc (
  id bigint generated by default as identity primary key,
  filial_contexto_id bigint not null references public.filiais(id) on delete restrict,
  chave_origem text not null,
  numero_venda text,
  cliente text,
  descricao_plano text,
  vendedor_ixc_id text,
  filial_ixc_id text,
  motivo text not null,
  dados_origem jsonb not null,
  situacao text not null default 'pendente'
    check (situacao in ('pendente', 'importada', 'descartada')),
  criado_em timestamptz not null default now(),
  resolvido_em timestamptz,
  resolvido_por uuid,
  venda_id bigint references public.vendas(id) on delete set null,
  unique (filial_contexto_id, chave_origem)
);

create index if not exists vendas_importacao_revisao_ixc_pendentes_idx
  on public.vendas_importacao_revisao_ixc (filial_contexto_id, criado_em desc)
  where situacao = 'pendente';

alter table public.vendas_importacao_revisao_ixc enable row level security;
drop policy if exists vendas_importacao_revisao_ixc_select on public.vendas_importacao_revisao_ixc;
create policy vendas_importacao_revisao_ixc_select on public.vendas_importacao_revisao_ixc
  for select to authenticated using (private.admin_tem_acesso_filial(filial_contexto_id));
drop policy if exists vendas_importacao_revisao_ixc_insert on public.vendas_importacao_revisao_ixc;
create policy vendas_importacao_revisao_ixc_insert on public.vendas_importacao_revisao_ixc
  for insert to authenticated with check (private.admin_tem_acesso_filial(filial_contexto_id));
drop policy if exists vendas_importacao_revisao_ixc_update on public.vendas_importacao_revisao_ixc;
create policy vendas_importacao_revisao_ixc_update on public.vendas_importacao_revisao_ixc
  for update to authenticated using (private.admin_tem_acesso_filial(filial_contexto_id))
  with check (private.admin_tem_acesso_filial(filial_contexto_id));
revoke all on table public.vendas_importacao_revisao_ixc from anon, authenticated;
grant select, insert, update on table public.vendas_importacao_revisao_ixc to authenticated;
grant usage, select on sequence public.vendas_importacao_revisao_ixc_id_seq to authenticated;

create or replace function public.registrar_venda_ixc_com_revisao(
  p_venda jsonb,
  p_revisao jsonb
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_filial_contexto bigint;
  v_vendedor_id bigint;
  v_origem bigint;
  v_destino bigint;
  v_plano bigint;
  v_data timestamptz;
  v_valor numeric;
  v_numero text;
  v_venda_id bigint;
  v_chave text;
  v_revisao_existente public.vendas_importacao_revisao_ixc%rowtype;
begin
  if auth.uid() is null then raise exception 'É necessário entrar no painel administrativo.'; end if;
  v_filial_contexto := nullif(p_revisao->>'filial_contexto_id', '')::bigint;
  v_vendedor_id := nullif(p_venda->>'vendedor_id', '')::bigint;
  v_origem := nullif(p_venda->>'filial_origem_id', '')::bigint;
  v_destino := nullif(p_venda->>'filial_destino_id', '')::bigint;
  v_plano := nullif(p_venda->>'plano_id', '')::bigint;
  v_data := nullif(p_venda->>'data_venda', '')::timestamptz;
  v_valor := nullif(p_venda->>'valor', '')::numeric;
  v_numero := nullif(btrim(coalesce(p_venda->>'numero_venda', '')), '');
  v_chave := nullif(btrim(coalesce(p_revisao->>'chave_origem', '')), '');
  if v_filial_contexto is null or v_origem is null or v_destino is null or v_data is null
     or v_valor is null or v_valor < 0 or v_numero is null or v_numero !~ '^\d+$' or v_chave is null then
    raise exception 'Confira filial, contrato, data e valor antes de importar.';
  end if;
  if not private.admin_tem_acesso_filial(v_filial_contexto) or not private.admin_tem_acesso_filial(v_destino) then
    raise exception 'Sua conta não tem acesso à filial desta venda.';
  end if;
  if not private.admin_e_superadmin() and not private.admin_tem_acesso_filial(v_origem) then
    raise exception 'Sua conta não tem acesso à filial de origem desta venda.';
  end if;
  if v_vendedor_id is not null and not exists (
    select 1 from public.vendedores x where x.id = v_vendedor_id and x.filial_id = v_origem
  ) then raise exception 'O vendedor precisa pertencer à filial de origem.'; end if;
  if v_plano is not null and not exists (select 1 from public.planos x where x.id = v_plano) then
    raise exception 'Plano não encontrado no catálogo.';
  end if;
  if exists (select 1 from public.vendas x where btrim(coalesce(x.numero_venda, '')) = v_numero) then
    raise exception 'Este contrato já está registrado em outra venda.';
  end if;
  select * into v_revisao_existente from public.vendas_importacao_revisao_ixc x
  where x.filial_contexto_id = v_filial_contexto and x.chave_origem = v_chave
  for update;
  if found and (v_revisao_existente.situacao <> 'pendente' or v_revisao_existente.venda_id is not null) then
    raise exception 'Esta linha do relatório já foi importada ou enviada para revisão.';
  end if;

  insert into public.vendas (
    vendedor_id, filial_origem_id, filial_destino_id, plano_id, data_venda,
    valor, cliente, numero_venda, observacao, fora_filial
  ) values (
    v_vendedor_id, v_origem, v_destino, v_plano, v_data, v_valor,
    nullif(btrim(coalesce(p_venda->>'cliente', '')), ''), v_numero,
    nullif(btrim(coalesce(p_venda->>'observacao', '')), ''),
    coalesce((p_venda->>'fora_filial')::boolean, false)
  ) returning id into v_venda_id;

  if v_revisao_existente.id is not null then
    update public.vendas_importacao_revisao_ixc
    set numero_venda = v_numero,
        cliente = nullif(btrim(coalesce(p_venda->>'cliente', '')), ''),
        descricao_plano = nullif(btrim(coalesce(p_revisao->>'descricao_plano', '')), ''),
        vendedor_ixc_id = nullif(btrim(coalesce(p_revisao->>'vendedor_ixc_id', '')), ''),
        filial_ixc_id = nullif(btrim(coalesce(p_revisao->>'filial_ixc_id', '')), ''),
        motivo = coalesce(nullif(btrim(coalesce(p_revisao->>'motivo', '')), ''), 'Dados importados com vínculo pendente.'),
        dados_origem = coalesce(p_revisao->'dados_origem', '{}'::jsonb),
        venda_id = v_venda_id
    where id = v_revisao_existente.id;
  else
    insert into public.vendas_importacao_revisao_ixc (
      filial_contexto_id, chave_origem, numero_venda, cliente, descricao_plano,
      vendedor_ixc_id, filial_ixc_id, motivo, dados_origem, venda_id
    ) values (
      v_filial_contexto, v_chave, v_numero,
      nullif(btrim(coalesce(p_venda->>'cliente', '')), ''),
      nullif(btrim(coalesce(p_revisao->>'descricao_plano', '')), ''),
      nullif(btrim(coalesce(p_revisao->>'vendedor_ixc_id', '')), ''),
      nullif(btrim(coalesce(p_revisao->>'filial_ixc_id', '')), ''),
      coalesce(nullif(btrim(coalesce(p_revisao->>'motivo', '')), ''), 'Dados importados com vínculo pendente.'),
      coalesce(p_revisao->'dados_origem', '{}'::jsonb), v_venda_id
    );
  end if;
  return v_venda_id;
end;
$function$;

revoke all on function public.registrar_venda_ixc_com_revisao(jsonb, jsonb) from public, anon;
grant execute on function public.registrar_venda_ixc_com_revisao(jsonb, jsonb) to authenticated;

create or replace function public.importar_revisao_venda_ixc(
  p_revisao_id bigint,
  p_venda jsonb
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_revisao public.vendas_importacao_revisao_ixc%rowtype;
  v_vendedor_id bigint;
  v_origem bigint;
  v_destino bigint;
  v_plano bigint;
  v_data timestamptz;
  v_valor numeric;
  v_numero text;
  v_venda_id bigint;
begin
  if auth.uid() is null then raise exception 'É necessário entrar no painel administrativo.'; end if;
  select * into v_revisao from public.vendas_importacao_revisao_ixc
    where id = p_revisao_id for update;
  if not found or v_revisao.situacao <> 'pendente' then
    raise exception 'Esta linha não está mais aguardando revisão.';
  end if;
  if not private.admin_tem_acesso_filial(v_revisao.filial_contexto_id) then
    raise exception 'Sua conta não tem acesso a esta filial.';
  end if;

  v_vendedor_id := nullif(p_venda->>'vendedor_id', '')::bigint;
  v_origem := nullif(p_venda->>'filial_origem_id', '')::bigint;
  v_destino := nullif(p_venda->>'filial_destino_id', '')::bigint;
  v_plano := nullif(p_venda->>'plano_id', '')::bigint;
  v_data := nullif(p_venda->>'data_venda', '')::timestamptz;
  v_valor := nullif(p_venda->>'valor', '')::numeric;
  v_numero := nullif(btrim(coalesce(p_venda->>'numero_venda', '')), '');
  if v_vendedor_id is null or v_origem is null or v_destino is null or v_plano is null
     or v_data is null or v_valor is null or v_valor < 0 or v_numero is null or v_numero !~ '^\d+$' then
    raise exception 'Preencha vendedor, plano, filiais, data, contrato e valor antes de importar.';
  end if;
  if not private.admin_tem_acesso_filial(v_destino) then
    raise exception 'Sua conta não tem acesso à filial de destino selecionada.';
  end if;
  if not private.admin_e_superadmin() and not private.admin_tem_acesso_filial(v_origem) then
    raise exception 'Sua conta não tem acesso à filial de origem selecionada.';
  end if;
  if not exists (select 1 from public.vendedores x where x.id = v_vendedor_id and x.filial_id = v_origem) then
    raise exception 'O vendedor selecionado não pertence à filial de origem.';
  end if;
  if not exists (select 1 from public.planos x where x.id = v_plano) then
    raise exception 'O plano selecionado não existe mais no catálogo.';
  end if;
  if exists (
    select 1 from public.vendas x
    where btrim(coalesce(x.numero_venda, '')) = v_numero
      and (v_revisao.venda_id is null or x.id <> v_revisao.venda_id)
  ) then
    raise exception 'Este contrato já está registrado em outra venda.';
  end if;

  if v_revisao.venda_id is null then
    insert into public.vendas (
      vendedor_id, filial_origem_id, filial_destino_id, plano_id, data_venda,
      valor, cliente, numero_venda, observacao, fora_filial
    ) values (
      v_vendedor_id, v_origem, v_destino, v_plano, v_data, v_valor,
      nullif(btrim(coalesce(p_venda->>'cliente', '')), ''), v_numero,
      nullif(btrim(coalesce(p_venda->>'observacao', '')), ''),
      coalesce((p_venda->>'fora_filial')::boolean, false)
    ) returning id into v_venda_id;
  else
    update public.vendas
    set vendedor_id = v_vendedor_id, filial_origem_id = v_origem,
        filial_destino_id = v_destino, plano_id = v_plano, data_venda = v_data,
        valor = v_valor, cliente = nullif(btrim(coalesce(p_venda->>'cliente', '')), ''),
        numero_venda = v_numero, observacao = nullif(btrim(coalesce(p_venda->>'observacao', '')), ''),
        fora_filial = coalesce((p_venda->>'fora_filial')::boolean, false)
    where id = v_revisao.venda_id;
    if not found then raise exception 'A venda importada não foi encontrada.'; end if;
    v_venda_id := v_revisao.venda_id;
  end if;

  update public.vendas_importacao_revisao_ixc
  set situacao = 'importada',
      resolvido_em = now(), resolvido_por = auth.uid()
  where id = p_revisao_id;
  return v_venda_id;
end;
$function$;

revoke all on function public.importar_revisao_venda_ixc(bigint, jsonb) from public, anon;
grant execute on function public.importar_revisao_venda_ixc(bigint, jsonb) to authenticated;
notify pgrst, 'reload schema';

commit;
