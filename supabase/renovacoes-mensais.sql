-- Estrutura para metas individuais e totais mensais de renovações.
-- Execute no SQL Editor do Supabase antes de usar a nova aba Renovações.
begin;

do $check$
begin
  if to_regprocedure('private.admin_tem_acesso_filial(bigint)') is null then
    raise exception 'Aplique primeiro supabase/regional-access.sql para configurar o isolamento por filial.';
  end if;
end;
$check$;

create table if not exists public.metas_renovacao_individual (
  id bigint generated by default as identity primary key,
  filial_id bigint not null references public.filiais(id) on delete cascade,
  vendedor_id bigint not null references public.vendedores(id) on delete cascade,
  mes integer not null check (mes between 1 and 12),
  ano integer not null check (ano between 2000 and 2200),
  meta_m3 integer check (meta_m3 is null or meta_m3 >= 0),
  meta_m2 integer check (meta_m2 is null or meta_m2 >= 0),
  meta_m1 integer check (meta_m1 is null or meta_m1 >= 0),
  atualizado_em timestamptz not null default now(),
  constraint metas_renovacao_individual_vendedor_mes_key unique (vendedor_id, mes, ano)
);

create table if not exists public.metas_renovacao_filial (
  id bigint generated by default as identity primary key,
  filial_id bigint not null references public.filiais(id) on delete cascade,
  mes integer not null check (mes between 1 and 12),
  ano integer not null check (ano between 2000 and 2200),
  meta_m3 integer check (meta_m3 is null or meta_m3 >= 0),
  meta_m2 integer check (meta_m2 is null or meta_m2 >= 0),
  meta_m1 integer check (meta_m1 is null or meta_m1 >= 0),
  atualizado_em timestamptz not null default now(),
  constraint metas_renovacao_filial_mes_key unique (filial_id, mes, ano)
);

-- Copia as metas gerais antigas para a nova tabela, sem apagar nem alterar
-- a linha legada que também guarda os limites de cancelamento.
insert into public.metas_renovacao_filial (filial_id, mes, ano, meta_m3, meta_m2, meta_m1)
select filial_id, mes, ano, renovacoes_meta_m3, renovacoes_meta_m2, renovacoes_meta_m1
from public.metas_renovacao_cancelamento
on conflict (filial_id, mes, ano) do nothing;

create table if not exists public.renovacoes_mensais (
  id bigint generated by default as identity primary key,
  filial_id bigint not null references public.filiais(id) on delete cascade,
  vendedor_id bigint not null references public.vendedores(id) on delete cascade,
  mes integer not null check (mes between 1 and 12),
  ano integer not null check (ano between 2000 and 2200),
  quantidade integer not null check (quantidade >= 0),
  arquivo_origem text,
  importado_em timestamptz not null default now(),
  constraint renovacoes_mensais_vendedor_mes_key unique (filial_id, vendedor_id, mes, ano)
);

-- Detalhamento de cada evento de renovação, para auditoria e relatórios por vendedor.
create table if not exists public.renovacoes_registros (
  id bigint generated by default as identity primary key,
  filial_id bigint not null references public.filiais(id) on delete cascade,
  vendedor_id bigint not null references public.vendedores(id) on delete cascade,
  mes integer not null check (mes between 1 and 12),
  ano integer not null check (ano between 2000 and 2200),
  contrato text not null,
  cliente text not null,
  plano text not null,
  valor numeric(12,2) not null check (valor >= 0),
  data_renovacao date not null,
  arquivo_origem text,
  importado_em timestamptz not null default now(),
  constraint renovacoes_registros_filial_mes_contrato_key unique (filial_id, mes, ano, contrato)
);

-- Metadados para a fila de conferência: mesmo sem preço reconhecido, a
-- renovação permanece registrada e conta nos totais desde a importação.
alter table public.renovacoes_registros
  add column if not exists plano_id bigint references public.planos(id) on delete set null,
  add column if not exists conferencia_pendente boolean not null default false;

alter table public.metas_renovacao_individual enable row level security;
alter table public.metas_renovacao_filial enable row level security;
alter table public.renovacoes_mensais enable row level security;
alter table public.renovacoes_registros enable row level security;

drop policy if exists metas_renovacao_filial_public_read on public.metas_renovacao_filial;
create policy metas_renovacao_filial_public_read on public.metas_renovacao_filial
  for select to anon, authenticated using (true);
drop policy if exists metas_renovacao_filial_admin_write on public.metas_renovacao_filial;
create policy metas_renovacao_filial_admin_write on public.metas_renovacao_filial
  for all to authenticated using (private.admin_tem_acesso_filial(filial_id))
  with check (private.admin_tem_acesso_filial(filial_id));

drop policy if exists renovacao_individual_admin_write on public.metas_renovacao_individual;
create policy renovacao_individual_admin_write on public.metas_renovacao_individual
  for all to authenticated
  using (private.admin_tem_acesso_filial(filial_id))
  with check (
    private.admin_tem_acesso_filial(filial_id)
    and exists (select 1 from public.vendedores v where v.id = vendedor_id and v.filial_id = metas_renovacao_individual.filial_id)
  );

drop policy if exists renovacoes_mensais_admin_write on public.renovacoes_mensais;
create policy renovacoes_mensais_admin_write on public.renovacoes_mensais
  for all to authenticated
  using (private.admin_tem_acesso_filial(filial_id))
  with check (
    private.admin_tem_acesso_filial(filial_id)
    and exists (select 1 from public.vendedores v where v.id = vendedor_id)
  );

drop policy if exists renovacoes_registros_admin_access on public.renovacoes_registros;
create policy renovacoes_registros_admin_access on public.renovacoes_registros
  for all to authenticated
  using (private.admin_tem_acesso_filial(filial_id))
  with check (
    private.admin_tem_acesso_filial(filial_id)
    and exists (select 1 from public.vendedores v where v.id = vendedor_id)
  );

grant select on public.metas_renovacao_filial to anon, authenticated;
grant select, insert, update, delete on public.metas_renovacao_filial, public.metas_renovacao_individual, public.renovacoes_mensais to authenticated;
grant select, insert, update, delete on public.renovacoes_registros to authenticated;
grant usage, select on sequence public.metas_renovacao_filial_id_seq, public.metas_renovacao_individual_id_seq, public.renovacoes_mensais_id_seq, public.renovacoes_registros_id_seq to authenticated;

-- A página pública recebe apenas o total da regional; os números por
-- vendedor continuam legíveis somente para administradores da filial.
create or replace function public.total_renovacoes_mensais(p_filial_id bigint, p_mes integer, p_ano integer)
returns bigint
language sql stable security definer set search_path = ''
as $function$
  select sum(r.quantidade)::bigint
  from public.renovacoes_mensais r
  where r.filial_id = p_filial_id and r.mes = p_mes and r.ano = p_ano;
$function$;
revoke all on function public.total_renovacoes_mensais(bigint, integer, integer) from public;
grant execute on function public.total_renovacoes_mensais(bigint, integer, integer) to anon, authenticated;

-- O painel público recebe apenas o top 5 agregado, mantendo os registros
-- detalhados por vendedor acessíveis somente aos administradores da filial.
create or replace function public.destaques_renovacoes_mensais(
  p_filial_id bigint, p_mes integer, p_ano integer
)
returns table (posicao bigint, vendedor_id bigint, vendedor_nome text, tipo text, quantidade bigint)
language sql stable security definer set search_path = ''
as $function$
  select dense_rank() over (order by sum(r.quantidade) desc), v.id, v.nome, v.tipo::text, sum(r.quantidade)::bigint
  from public.renovacoes_mensais r
  join public.vendedores v on v.id = r.vendedor_id and v.filial_id = r.filial_id
    and v.ativo is true and coalesce(v.participa_ranking, true) is true
  where r.filial_id = p_filial_id and r.mes = p_mes and r.ano = p_ano and r.quantidade > 0
  group by v.id, v.nome, v.tipo
  order by sum(r.quantidade) desc, v.nome asc
  limit 5;
$function$;
revoke all on function public.destaques_renovacoes_mensais(bigint, integer, integer) from public;
grant execute on function public.destaques_renovacoes_mensais(bigint, integer, integer) to anon, authenticated;

create or replace function public.substituir_renovacoes_mensais(
  p_filial_id bigint, p_mes integer, p_ano integer, p_arquivo text, p_linhas jsonb
)
returns integer
language plpgsql security definer set search_path = ''
as $function$
declare
  linhas_inseridas integer;
begin
  if auth.uid() is null or not private.admin_tem_acesso_filial(p_filial_id) then
    raise exception 'Sem permissão para atualizar renovações desta filial.' using errcode = '42501';
  end if;
  if p_mes < 1 or p_mes > 12 or p_ano < 2000 or p_ano > 2200 or p_linhas is null or jsonb_typeof(p_linhas) <> 'array' then
    raise exception 'Mês, ano ou linhas do relatório inválidos.' using errcode = '22023';
  end if;
  perform pg_advisory_xact_lock(p_filial_id::integer, p_ano * 12 + p_mes);
  if exists (
    select 1
    from jsonb_to_recordset(p_linhas) as r(vendedor_id bigint, quantidade integer)
    left join public.vendedores v on v.id = r.vendedor_id
    where v.id is null or v.filial_id <> p_filial_id or r.quantidade is null or r.quantidade < 0
  ) then
    raise exception 'O relatório contém vendedores fora da filial ou quantidades inválidas.' using errcode = '22023';
  end if;

  delete from public.renovacoes_mensais
  where filial_id = p_filial_id and mes = p_mes and ano = p_ano;

  insert into public.renovacoes_mensais (filial_id, vendedor_id, mes, ano, quantidade, arquivo_origem)
  select p_filial_id, r.vendedor_id, p_mes, p_ano, r.quantidade, left(p_arquivo, 255)
  from jsonb_to_recordset(p_linhas) as r(vendedor_id bigint, quantidade integer)
  where r.quantidade > 0;

  get diagnostics linhas_inseridas = row_count;
  return linhas_inseridas;
end;
$function$;
revoke all on function public.substituir_renovacoes_mensais(bigint, integer, integer, text, jsonb) from public, anon;
grant execute on function public.substituir_renovacoes_mensais(bigint, integer, integer, text, jsonb) to authenticated;

-- A substituição do detalhamento e a atualização dos totais ocorrem na mesma
-- transação. Os totais continuam servindo aos indicadores públicos agregados.
create or replace function public.substituir_registros_renovacao(
  p_filial_id bigint, p_mes integer, p_ano integer, p_arquivo text, p_linhas jsonb
)
returns integer
language plpgsql security definer set search_path = ''
as $function$
declare
  linhas_inseridas integer;
begin
  if auth.uid() is null or not private.admin_tem_acesso_filial(p_filial_id) then
    raise exception 'Sem permissão para atualizar renovações desta filial.' using errcode = '42501';
  end if;
  if p_mes < 1 or p_mes > 12 or p_ano < 2000 or p_ano > 2200 or p_linhas is null or jsonb_typeof(p_linhas) <> 'array' then
    raise exception 'Mês, ano ou linhas do relatório inválidos.' using errcode = '22023';
  end if;
  if exists (
    select 1 from jsonb_to_recordset(p_linhas) as r(vendedor_id bigint, contrato text, cliente text, plano text, plano_id bigint, valor numeric, data date, conferencia_pendente boolean)
    left join public.vendedores v on v.id = r.vendedor_id
    where v.id is null or nullif(trim(r.contrato), '') is null
      or nullif(trim(r.cliente), '') is null or nullif(trim(r.plano), '') is null
      or r.valor is null or r.valor < 0 or r.data is null
      or r.conferencia_pendente is null
      or (r.plano_id is not null and not exists (select 1 from public.planos p where p.id = r.plano_id))
      or extract(month from r.data)::integer <> p_mes or extract(year from r.data)::integer <> p_ano
  ) then
    raise exception 'O relatório contém dados inválidos ou data fora do mês.' using errcode = '22023';
  end if;

  insert into public.renovacoes_registros (filial_id, vendedor_id, mes, ano, contrato, cliente, plano, plano_id, valor, data_renovacao, conferencia_pendente, arquivo_origem)
  select p_filial_id, r.vendedor_id, p_mes, p_ano, regexp_replace(trim(r.contrato), '\s+', '', 'g'), trim(r.cliente), trim(r.plano), r.plano_id, r.valor, r.data, r.conferencia_pendente, left(p_arquivo, 255)
  from jsonb_to_recordset(p_linhas) as r(vendedor_id bigint, contrato text, cliente text, plano text, plano_id bigint, valor numeric, data date, conferencia_pendente boolean)
  on conflict (filial_id, mes, ano, contrato) do nothing;
  get diagnostics linhas_inseridas = row_count;

  -- Preserva agregados antigos sem detalhamento enquanto contratos do
  -- relatório completo são incorporados à tabela de registros.
  insert into public.renovacoes_mensais (filial_id, vendedor_id, mes, ano, quantidade, arquivo_origem)
  select p_filial_id, vendedor_id, p_mes, p_ano, count(*)::integer, left(p_arquivo, 255)
  from public.renovacoes_registros
  where filial_id = p_filial_id and mes = p_mes and ano = p_ano
  group by vendedor_id
  on conflict (filial_id, vendedor_id, mes, ano) do update
    set quantidade = greatest(public.renovacoes_mensais.quantidade, excluded.quantidade),
        arquivo_origem = excluded.arquivo_origem,
        importado_em = now();
  return linhas_inseridas;
end;
$function$;
revoke all on function public.substituir_registros_renovacao(bigint, integer, integer, text, jsonb) from public, anon;
grant execute on function public.substituir_registros_renovacao(bigint, integer, integer, text, jsonb) to authenticated;

create or replace function public.resolver_conferencia_renovacao(
  p_registro_id bigint, p_plano_id bigint, p_plano text, p_valor numeric
)
returns void
language plpgsql security definer set search_path = ''
as $function$
declare
  v_filial_id bigint;
  v_nome_plano text;
begin
  if auth.uid() is null then
    raise exception 'Autenticação administrativa necessária.' using errcode = '42501';
  end if;
  if p_valor is null or p_valor < 0 or nullif(trim(p_plano), '') is null then
    raise exception 'Plano e valor da renovação inválidos.' using errcode = '22023';
  end if;
  select p.nome into v_nome_plano from public.planos p where p.id = p_plano_id;
  if v_nome_plano is null then
    raise exception 'O plano selecionado não existe no catálogo.' using errcode = '22023';
  end if;
  select filial_id into v_filial_id
  from public.renovacoes_registros
  where id = p_registro_id and conferencia_pendente = true;
  if v_filial_id is null or not private.admin_tem_acesso_filial(v_filial_id) then
    raise exception 'Renovação pendente não encontrada ou sem acesso à filial.' using errcode = '42501';
  end if;
  update public.renovacoes_registros
  set plano_id = p_plano_id, plano = v_nome_plano, valor = p_valor, conferencia_pendente = false
  where id = p_registro_id and conferencia_pendente = true;
end;
$function$;
revoke all on function public.resolver_conferencia_renovacao(bigint, bigint, text, numeric) from public, anon;
grant execute on function public.resolver_conferencia_renovacao(bigint, bigint, text, numeric) to authenticated;

commit;
notify pgrst, 'reload schema';
