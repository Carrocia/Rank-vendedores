-- Fundação do sistema de ranks de carreira.
-- Execute depois de regional-access.sql e das migrações atuais de vendedores.
-- Esta etapa cria identidade persistente e histórico agregado, sem dados pessoais
-- de clientes/contratos. O cálculo mensal e a consolidação automática serão
-- habilitados pela próxima etapa da implementação.

begin;

do $check$
begin
  if to_regprocedure('private.admin_e_superadmin()') is null
     or to_regprocedure('private.admin_tem_acesso_filial(bigint)') is null then
    raise exception 'Aplique primeiro supabase/regional-access.sql.';
  end if;
end;
$check$;

alter table public.vendedores
  add column if not exists carreira_pessoa_id uuid default gen_random_uuid();

update public.vendedores
set carreira_pessoa_id = gen_random_uuid()
where carreira_pessoa_id is null;

alter table public.vendedores
  alter column carreira_pessoa_id set default gen_random_uuid(),
  alter column carreira_pessoa_id set not null;

create index if not exists vendedores_carreira_pessoa_idx
  on public.vendedores (carreira_pessoa_id);

create table if not exists public.ranks_carreira_mensais (
  id bigint generated by default as identity primary key,
  carreira_pessoa_id uuid not null,
  mes integer not null check (mes between 1 and 12),
  ano integer not null check (ano between 2000 and 2200),
  vendas integer not null default 0 check (vendas >= 0),
  valor_vendas numeric(14,2) not null default 0 check (valor_vendas >= 0),
  meta_vendas integer check (meta_vendas is null or meta_vendas >= 0),
  renovacoes integer not null default 0 check (renovacoes >= 0),
  meta_renovacoes integer check (meta_renovacoes is null or meta_renovacoes >= 0),
  ticket_medio numeric(14,2),
  ticket_referencia numeric(14,2),
  rank_mensal text check (rank_mensal is null or rank_mensal in ('D','C','B','A','S','SS')),
  elegivel boolean not null default false,
  consolidado_em timestamptz,
  atualizado_em timestamptz not null default now(),
  constraint ranks_carreira_mensais_pessoa_mes_key unique (carreira_pessoa_id, mes, ano)
);

create index if not exists ranks_carreira_mensais_periodo_idx
  on public.ranks_carreira_mensais (ano desc, mes desc, carreira_pessoa_id);

alter table public.ranks_carreira_mensais enable row level security;

drop policy if exists ranks_carreira_mensais_select_scope on public.ranks_carreira_mensais;
create policy ranks_carreira_mensais_select_scope
  on public.ranks_carreira_mensais for select to authenticated
  using (
    exists (
      select 1
      from public.vendedores v
      where v.carreira_pessoa_id = ranks_carreira_mensais.carreira_pessoa_id
        and private.admin_tem_acesso_filial(v.filial_id)
    )
  );

-- O navegador só pode ler métricas agregadas; gravações serão feitas por
-- funções controladas do banco, nunca por valores enviados pelo cliente.
revoke all on public.ranks_carreira_mensais from public, anon, authenticated;
grant select on public.ranks_carreira_mensais to authenticated;

create or replace function public.vincular_identidade_carreira(
  p_vendedor_novo bigint,
  p_vendedor_referencia bigint
)
returns uuid
language plpgsql security definer set search_path = ''
as $function$
declare
  v_identidade_referencia uuid;
  v_identidade_nova uuid;
begin
  if auth.uid() is null or not private.admin_e_superadmin() then
    raise exception 'Somente o superadministrador pode vincular identidades de carreira.'
      using errcode = '42501';
  end if;
  if p_vendedor_novo is null or p_vendedor_referencia is null
     or p_vendedor_novo = p_vendedor_referencia then
    raise exception 'Selecione dois cadastros diferentes.' using errcode = '22023';
  end if;

  select carreira_pessoa_id into v_identidade_nova
  from public.vendedores where id = p_vendedor_novo for update;
  select carreira_pessoa_id into v_identidade_referencia
  from public.vendedores where id = p_vendedor_referencia;

  if v_identidade_nova is null or v_identidade_referencia is null then
    raise exception 'Um dos cadastros de vendedor não foi encontrado.' using errcode = '22023';
  end if;
  if v_identidade_nova = v_identidade_referencia then
    return v_identidade_referencia;
  end if;
  if exists (
    select 1 from public.ranks_carreira_mensais
    where carreira_pessoa_id = v_identidade_nova
  ) then
    raise exception 'Este cadastro já tem histórico de carreira. Faça a vinculação antes do primeiro fechamento mensal.'
      using errcode = '23514';
  end if;

  update public.vendedores
  set carreira_pessoa_id = v_identidade_referencia
  where id = p_vendedor_novo;

  return v_identidade_referencia;
end;
$function$;

revoke all on function public.vincular_identidade_carreira(bigint, bigint) from public, anon;
grant execute on function public.vincular_identidade_carreira(bigint, bigint) to authenticated;

commit;
notify pgrst, 'reload schema';
