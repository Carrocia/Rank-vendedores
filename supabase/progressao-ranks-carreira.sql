-- Fundação do sistema de ranks de carreira.
-- Execute depois de regional-access.sql e das migrações atuais de vendedores.
-- Esta etapa cria identidade persistente e histórico agregado, sem dados pessoais
-- de clientes/contratos. O cálculo do mês corrente usa os dados já registrados;
-- a consolidação automática dos meses encerrados será habilitada em etapa futura.

begin;

do $check$
begin
  if to_regprocedure('private.admin_e_superadmin()') is null
     or to_regprocedure('private.admin_tem_acesso_filial(bigint)') is null then
    raise exception 'Aplique primeiro supabase/regional-access.sql.';
  end if;
end;
$check$;

alter table public.vendedores
  add column if not exists carreira_pessoa_id uuid default gen_random_uuid();

update public.vendedores
set carreira_pessoa_id = gen_random_uuid()
where carreira_pessoa_id is null;

alter table public.vendedores
  alter column carreira_pessoa_id set default gen_random_uuid(),
  alter column carreira_pessoa_id set not null;

create index if not exists vendedores_carreira_pessoa_idx
  on public.vendedores (carreira_pessoa_id);

create table if not exists public.ranks_carreira_mensais (
  id bigint generated by default as identity primary key,
  carreira_pessoa_id uuid not null,
  mes integer not null check (mes between 1 and 12),
  ano integer not null check (ano between 2000 and 2200),
  vendas integer not null default 0 check (vendas >= 0),
  valor_vendas numeric(14,2) not null default 0 check (valor_vendas >= 0),
  meta_vendas integer check (meta_vendas is null or meta_vendas >= 0),
  renovacoes integer not null default 0 check (renovacoes >= 0),
  meta_renovacoes integer check (meta_renovacoes is null or meta_renovacoes >= 0),
  ticket_medio numeric(14,2),
  ticket_referencia numeric(14,2),
  rank_mensal text check (rank_mensal is null or rank_mensal in ('D','C','B','A','S','SS')),
  elegivel boolean not null default false,
  m1_vendas boolean not null default false,
  m1_renovacoes boolean not null default false,
  consolidado_em timestamptz,
  atualizado_em timestamptz not null default now(),
  constraint ranks_carreira_mensais_pessoa_mes_key unique (carreira_pessoa_id, mes, ano)
);

create index if not exists ranks_carreira_mensais_periodo_idx
  on public.ranks_carreira_mensais (ano desc, mes desc, carreira_pessoa_id);

alter table public.ranks_carreira_mensais enable row level security;

drop policy if exists ranks_carreira_mensais_select_scope on public.ranks_carreira_mensais;
create policy ranks_carreira_mensais_select_scope
  on public.ranks_carreira_mensais for select to authenticated
  using (
    exists (
      select 1
      from public.vendedores v
      where v.carreira_pessoa_id = ranks_carreira_mensais.carreira_pessoa_id
        and private.admin_tem_acesso_filial(v.filial_id)
    )
  );

-- O navegador só pode ler métricas agregadas; gravações serão feitas por
-- funções controladas do banco, nunca por valores enviados pelo cliente.
revoke all on public.ranks_carreira_mensais from public, anon, authenticated;
grant select on public.ranks_carreira_mensais to authenticated;

-- Cálculo do mês vigente diretamente das vendas e renovações já guardadas.
-- A função retorna somente totais por vendedor, sem cliente/contrato.
create or replace function public.calcular_rank_mensal_filial(
  p_filial_id bigint,
  p_mes integer,
  p_ano integer
)
returns table (
  carreira_pessoa_id uuid,
  vendedor_id bigint,
  vendedor_nome text,
  tipo text,
  vendas bigint,
  valor_vendas numeric,
  meta_vendas numeric,
  renovacoes bigint,
  meta_renovacoes numeric,
  ticket_medio numeric,
  ticket_referencia numeric,
  rank_mensal text,
  elegivel boolean,
  m1_vendas boolean,
  m1_renovacoes boolean
)
language plpgsql security definer set search_path = ''
as $function$
begin
  if auth.uid() is null or not private.admin_tem_acesso_filial(p_filial_id) then
    raise exception 'Sem permissão para calcular ranks desta regional.' using errcode = '42501';
  end if;
  if p_mes < 1 or p_mes > 12 or p_ano < 2000 or p_ano > 2200 then
    raise exception 'Mês ou ano inválido.' using errcode = '22023';
  end if;

  return query
  with vendedores_alvo as (
    select v.id, v.carreira_pessoa_id, v.nome, v.tipo, v.filial_id, v.ativo
    from public.vendedores v
    where v.filial_id = p_filial_id
      and v.ativo is true
      and coalesce(v.participa_ranking, true) is true
  ), pessoas_alvo as (
    select distinct va.carreira_pessoa_id from vendedores_alvo va
  ), vendedores_pessoa as (
    select v.id, v.carreira_pessoa_id, v.tipo, v.filial_id, v.ativo
    from public.vendedores v
    join pessoas_alvo pa on pa.carreira_pessoa_id = v.carreira_pessoa_id
  ), vendas_pessoa as (
    select vp.carreira_pessoa_id,
           count(sa.vendedor_id)::bigint as quantidade,
           coalesce(sum(sa.valor_total), 0)::numeric as valor
    from vendedores_pessoa vp
    left join public.vendas_admin sa
      on sa.vendedor_id = vp.id
     and sa.data_venda >= make_date(p_ano, p_mes, 1)
     and sa.data_venda < (make_date(p_ano, p_mes, 1) + interval '1 month')
     and (
       vp.tipo <> 'externo'
       or (
         sa.fora_filial is not true
         and sa.filial_origem_id = vp.filial_id
         and sa.filial_destino_id = vp.filial_id
       )
     )
    group by vp.carreira_pessoa_id
  ), renovacoes_pessoa as (
    select vp.carreira_pessoa_id, coalesce(sum(rm.quantidade), 0)::bigint as quantidade
    from vendedores_pessoa vp
    left join public.renovacoes_mensais rm
      on rm.vendedor_id = vp.id and rm.filial_id = vp.filial_id
     and rm.mes = p_mes and rm.ano = p_ano
    group by vp.carreira_pessoa_id
  ), filiais_alvo as (
    select distinct va.filial_id from vendedores_alvo va
  ), ticket_referencia_filial as (
    select fa.filial_id,
           (sum(sa.valor_total) / nullif(count(sa.vendedor_id), 0))::numeric as ticket
    from filiais_alvo fa
    left join public.vendas_admin sa
      on sa.filial_origem_id = fa.filial_id
     and sa.filial_destino_id = fa.filial_id
     and sa.fora_filial is not true
     and sa.data_venda >= make_date(p_ano, p_mes, 1)
     and sa.data_venda < (make_date(p_ano, p_mes, 1) + interval '1 month')
    group by fa.filial_id
  ), metricas as (
    select va.carreira_pessoa_id,
           va.id as vendedor_id,
           va.nome as vendedor_nome,
           va.tipo,
           coalesce(vp.quantidade, 0)::bigint as vendas,
           coalesce(vp.valor, 0)::numeric as valor_vendas,
           case
             when va.tipo = 'interno' then coalesce(m.meta_m1, 0)
             when va.ativo is true or m.id is not null then coalesce(m.meta_vendas, 0)
             else 0
           end::numeric as meta_vendas,
           case when va.tipo = 'externo' then 0 else coalesce(rp.quantidade, 0) end::bigint as renovacoes,
           case when va.tipo = 'externo' then null else coalesce(mr.meta_m1, 0) end::numeric as meta_renovacoes,
           case when coalesce(vp.quantidade, 0) > 0 then vp.valor / vp.quantidade else 0 end::numeric as ticket_medio,
           tr.ticket as ticket_referencia,
           (va.tipo = 'externo') as somente_externo,
           coalesce(rp.quantidade, 0)::bigint as renovacoes_reais
    from vendedores_alvo va
    left join vendas_pessoa vp on vp.carreira_pessoa_id = va.carreira_pessoa_id
    left join renovacoes_pessoa rp on rp.carreira_pessoa_id = va.carreira_pessoa_id
    left join ticket_referencia_filial tr on tr.filial_id = va.filial_id
    left join public.metas m
      on m.vendedor_id = va.id and m.mes = p_mes and m.ano = p_ano
    left join public.metas_renovacao_individual mr
      on mr.vendedor_id = va.id and mr.filial_id = va.filial_id
     and mr.mes = p_mes and mr.ano = p_ano
  ), elegibilidade as (
    select m.*,
      (coalesce(m.meta_vendas, 0) > 0) as pode_classificar,
      case when m.meta_vendas > 0 then m.vendas::numeric / m.meta_vendas else 0 end as pct_vendas,
      case when m.meta_renovacoes > 0 then m.renovacoes_reais::numeric / m.meta_renovacoes else 0 end as pct_renovacoes,
      coalesce(m.ticket_medio, 0)::numeric as ticket_medio_valido
    from metricas m
  )
  select e.carreira_pessoa_id,
         e.vendedor_id,
         e.vendedor_nome::text,
         e.tipo::text,
         e.vendas,
         e.valor_vendas,
         e.meta_vendas,
         e.renovacoes,
         e.meta_renovacoes,
         e.ticket_medio,
         e.ticket_referencia,
         case
           when not e.pode_classificar then null
           when e.pct_vendas >= 1.15 and (e.somente_externo or e.pct_renovacoes >= 0.80) and e.ticket_medio_valido >= 130 then 'S'
           when e.pct_vendas >= 1.00 and (e.somente_externo or e.pct_renovacoes >= 0.65) and e.ticket_medio_valido >= 120 then 'A'
           when e.pct_vendas >= 0.85 and (e.somente_externo or e.pct_renovacoes >= 0.45) and e.ticket_medio_valido >= 115 then 'B'
           when e.pct_vendas >= 0.70 and (e.somente_externo or e.pct_renovacoes >= 0.30) and e.ticket_medio_valido >= 110 then 'C'
           when e.pct_vendas >= 0.50 and e.ticket_medio_valido >= 105 then 'D'
           else null
         end::text as rank_mensal,
         e.pode_classificar as elegivel,
         case when e.somente_externo then e.vendas > 14 else e.meta_vendas > 0 and e.vendas >= e.meta_vendas end as m1_vendas,
         case when e.somente_externo then false else e.meta_renovacoes > 0 and e.renovacoes_reais >= e.meta_renovacoes end as m1_renovacoes
  from elegibilidade e
  order by e.tipo, e.vendedor_nome;
end;
$function$;

revoke all on function public.calcular_rank_mensal_filial(bigint, integer, integer) from public, anon;
grant execute on function public.calcular_rank_mensal_filial(bigint, integer, integer) to authenticated;

create or replace function public.vincular_identidade_carreira(
  p_vendedor_novo bigint,
  p_vendedor_referencia bigint
)
returns uuid
language plpgsql security definer set search_path = ''
as $function$
declare
  v_identidade_referencia uuid;
  v_identidade_nova uuid;
begin
  if auth.uid() is null or not private.admin_e_superadmin() then
    raise exception 'Somente o superadministrador pode vincular identidades de carreira.'
      using errcode = '42501';
  end if;
  if p_vendedor_novo is null or p_vendedor_referencia is null
     or p_vendedor_novo = p_vendedor_referencia then
    raise exception 'Selecione dois cadastros diferentes.' using errcode = '22023';
  end if;

  select carreira_pessoa_id into v_identidade_nova
  from public.vendedores where id = p_vendedor_novo for update;
  select carreira_pessoa_id into v_identidade_referencia
  from public.vendedores where id = p_vendedor_referencia;

  if v_identidade_nova is null or v_identidade_referencia is null then
    raise exception 'Um dos cadastros de vendedor não foi encontrado.' using errcode = '22023';
  end if;
  if v_identidade_nova = v_identidade_referencia then
    return v_identidade_referencia;
  end if;
  if exists (
    select 1 from public.ranks_carreira_mensais
    where carreira_pessoa_id = v_identidade_nova
  ) then
    raise exception 'Este cadastro já tem histórico de carreira. Faça a vinculação antes do primeiro fechamento mensal.'
      using errcode = '23514';
  end if;

  update public.vendedores
  set carreira_pessoa_id = v_identidade_referencia
  where id = p_vendedor_novo;

  return v_identidade_referencia;
end;
$function$;

revoke all on function public.vincular_identidade_carreira(bigint, bigint) from public, anon;
grant execute on function public.vincular_identidade_carreira(bigint, bigint) to authenticated;

commit;
notify pgrst, 'reload schema';
