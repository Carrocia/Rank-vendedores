create or replace function private.faixas_ticket_xp_validas(p_faixas jsonb)
returns boolean language plpgsql immutable set search_path = '' as $function$
declare
  v_faixa jsonb;
  v_min numeric;
  v_max numeric;
  v_anterior numeric;
  v_indice integer := 0;
  v_total integer;
begin
  if p_faixas is null or jsonb_typeof(p_faixas) <> 'array' then return false; end if;
  v_total := jsonb_array_length(p_faixas);
  if v_total = 0 then return false; end if;
  for v_faixa in select value from jsonb_array_elements(p_faixas) loop
    v_indice := v_indice + 1;
    if jsonb_typeof(v_faixa) <> 'object'
       or nullif(v_faixa->>'min', '') is null
       or nullif(v_faixa->>'multiplicador', '') is null then return false; end if;
    v_min := (v_faixa->>'min')::numeric;
    v_max := nullif(v_faixa->>'max', '')::numeric;
    if v_min < 0 or (v_indice = 1 and v_min <> 0)
       or (v_indice > 1 and v_min <> v_anterior)
       or (v_max is not null and v_max <= v_min)
       or (v_indice = v_total and v_max is not null)
       or (v_indice < v_total and v_max is null)
       or (v_faixa->>'multiplicador')::numeric <= 0 then return false; end if;
    v_anterior := v_max;
  end loop;
  return true;
exception when others then return false;
end;
$function$;

