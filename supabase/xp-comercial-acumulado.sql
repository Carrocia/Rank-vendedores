create or replace function private.auditar_campanha_xp_comercial()
returns trigger language plpgsql security definer set search_path = '' as $function$
declare
  v_hoje date := timezone('America/Manaus', now())::date;
begin
  if tg_op = 'INSERT' then
    if new.data_inicio <= v_hoje then
      raise exception 'Cadastre campanhas de XP antes da data de início; alterações retroativas precisam de processo de correção.' using errcode = '22023';
    end if;
    if new.faixas_ticket is not null and not private.faixas_ticket_xp_validas(new.faixas_ticket) then
      raise exception 'As faixas da campanha precisam ser contínuas, sem lacunas ou sobreposições.' using errcode = '22023';
    end if;
    insert into public.campanhas_xp_comercial_auditoria (campanha_id, evento, novo, alterado_por)
    values (new.id, 'criada', to_jsonb(new), auth.uid());
    return new;
  elsif tg_op = 'UPDATE' then
    if old.data_inicio <= v_hoje then
      raise exception 'Uma campanha iniciada não pode ser alterada retroativamente.' using errcode = '22023';
    end if;
    if new.faixas_ticket is not null and not private.faixas_ticket_xp_validas(new.faixas_ticket) then
      raise exception 'As faixas da campanha precisam ser contínuas, sem lacunas ou sobreposições.' using errcode = '22023';
    end if;
    insert into public.campanhas_xp_comercial_auditoria (campanha_id, evento, anterior, novo, alterado_por)
    values (new.id, 'alterada', to_jsonb(old), to_jsonb(new), auth.uid());
    return new;
  else
    if old.data_inicio <= v_hoje then
      raise exception 'Uma campanha iniciada não pode ser removida retroativamente.' using errcode = '22023';
    end if;
    insert into public.campanhas_xp_comercial_auditoria (campanha_id, evento, anterior, alterado_por)
    values (old.id, 'removida', to_jsonb(old), auth.uid());
    return old;
  end if;
end;
$function$;

