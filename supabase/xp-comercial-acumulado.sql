create or replace function public.calcular_xp_comercial_vendedor(
  p_vendedor_id bigint,
  p_mes integer,
  p_ano integer
)
returns table (
  carreira_pessoa_id uuid,
  vendedor_id bigint,
  mes integer,
  ano integer,
  tipo text,
  status text,
  vendas_novas integer,
  renovacoes integer,
  ticket_medio numeric,
  multiplicador_ticket numeric,
  xp_base_vendas numeric,
  xp_vendas_novas numeric,
  xp_bonus_ticket numeric,
  xp_renovacoes numeric,
  xp_bonus_meta_vendas numeric,
  xp_bonus_meta_renovacoes numeric,
  xp_total_periodo numeric,
  xp_acumulado_carreira numeric,
  bonus_metas_ativo boolean,
  faixa_ticket_aplicada jsonb,
  campanha_id bigint,
  calculado_em timestamptz
)
language plpgsql security definer set search_path = '' as $function$
declare
  v_vendedor public.vendedores%rowtype;
  v_config public.configuracao_xp_comercial%rowtype;
  v_periodo public.xp_comercial_periodos%rowtype;
  v_vendas integer := 0;
  v_renovacoes integer := 0;
  v_valor_vendas numeric := 0;
  v_ticket numeric;
  v_meta_vendas numeric := 0;
  v_meta_renovacoes numeric := 0;
  v_bonus_vendas numeric := 0;
  v_bonus_renovacoes numeric := 0;
  v_faixas jsonb;
  v_faixa jsonb;
  v_base_faixas text := 'valor_ticket';
  v_referencia numeric;
  v_ticket_comparacao numeric;
  v_multiplicador numeric;
  v_xp_base_vendas numeric;
  v_xp_vendas numeric;
  v_xp_bonus_ticket numeric;
  v_xp_renovacoes numeric;
  v_xp_total numeric;
  v_campanha_id bigint;
  v_campanhas_compatíveis integer := 0;
  v_fechado boolean := false;
  v_periodo_inicio date;
  v_periodo_fim date;
begin
  if auth.uid() is null then
    raise exception 'Autenticação administrativa necessária.' using errcode = '42501';
  end if;
  if p_mes < 1 or p_mes > 12 or p_ano < 2000 or p_ano > 2200 then
    raise exception 'Mês ou ano inválido.' using errcode = '22023';
  end if;
  select * into v_vendedor from public.vendedores where id = p_vendedor_id;
  if not found or not private.admin_tem_acesso_filial(v_vendedor.filial_id) then
    raise exception 'Vendedor não encontrado ou sem acesso à filial.' using errcode = '42501';
  end if;
  if v_vendedor.carreira_pessoa_id is null then
    raise exception 'O vendedor ainda não tem identidade de carreira.' using errcode = '22023';
  end if;
  select * into v_config from public.configuracao_xp_comercial where id = 1;
  if not found then raise exception 'Configuração central do XP não encontrada.'; end if;

  select * into v_periodo from public.xp_comercial_periodos p
  where p.carreira_pessoa_id = v_vendedor.carreira_pessoa_id and p.mes = p_mes and p.ano = p_ano
  for update;
  if found and v_periodo.status = 'fechado' then
    v_fechado := true;
  end if;

  if not v_fechado then
    v_periodo_inicio := make_date(p_ano, p_mes, 1);
    v_periodo_fim := (v_periodo_inicio + interval '1 month')::date;

    select count(*)::integer, coalesce(sum(sa.valor_total), 0)::numeric
      into v_vendas, v_valor_vendas
    from public.vendedores v
    join public.vendas_admin sa on sa.vendedor_id = v.id
      and sa.data_venda >= v_periodo_inicio
      and sa.data_venda < v_periodo_fim
      and (v.tipo <> 'externo' or (
        sa.fora_filial is not true
        and sa.filial_origem_id = v.filial_id
        and sa.filial_destino_id = v.filial_id
      ))
    where v.carreira_pessoa_id = v_vendedor.carreira_pessoa_id;

    select coalesce(sum(rm.quantidade), 0)::integer
      into v_renovacoes
    from public.vendedores v
    join public.renovacoes_mensais rm on rm.vendedor_id = v.id and rm.filial_id = v.filial_id
      and rm.mes = p_mes and rm.ano = p_ano
    where v.carreira_pessoa_id = v_vendedor.carreira_pessoa_id;

    if v_vendas > 0 then v_ticket := v_valor_vendas / v_vendas; else v_ticket := null; end if;

    select coalesce(sum(case when v.tipo = 'interno' then coalesce(m.meta_m1, 0) else coalesce(m.meta_vendas, 0) end), 0),
           coalesce(sum(case when v.tipo = 'externo' then 0 else coalesce(mr.meta_m1, 0) end), 0)
      into v_meta_vendas, v_meta_renovacoes
    from public.vendedores v
    left join public.metas m on m.vendedor_id = v.id and m.mes = p_mes and m.ano = p_ano
    left join public.metas_renovacao_individual mr on mr.vendedor_id = v.id and mr.filial_id = v.filial_id
      and mr.mes = p_mes and mr.ano = p_ano
    where v.carreira_pessoa_id = v_vendedor.carreira_pessoa_id;

    select count(*)::integer, (array_agg(c.id order by c.data_inicio desc, c.id desc))[1],
           (array_agg(c.faixas_ticket order by c.data_inicio desc, c.id desc))[1],
           (array_agg(c.base_faixas order by c.data_inicio desc, c.id desc))[1],
           (array_agg(c.referencia_ticket order by c.data_inicio desc, c.id desc))[1]
      into v_campanhas_compatíveis, v_campanha_id, v_faixas, v_base_faixas, v_referencia
    from public.campanhas_xp_comercial c
    where c.ativa is true and c.data_inicio < v_periodo_fim and c.data_fim > v_periodo_inicio
      and (c.tipos_vendedor is null or v_vendedor.tipo = any(c.tipos_vendedor))
      and (c.vendedores_ids is null or c.vendedores_ids && array(
        select v.id from public.vendedores v where v.carreira_pessoa_id = v_vendedor.carreira_pessoa_id
      ));
    if v_campanhas_compatíveis > 1 then
      raise exception 'Há campanhas de XP sobrepostas para este vendedor e período. Ajuste a configuração antes de calcular.' using errcode = '22023';
    end if;
    if v_campanhas_compatíveis = 0 then
      v_campanha_id := null;
      v_faixas := v_config.faixas_ticket;
      v_base_faixas := 'valor_ticket';
      v_referencia := null;
    elsif v_faixas is null then
      v_faixas := v_config.faixas_ticket;
      v_base_faixas := 'valor_ticket';
    end if;

    v_ticket_comparacao := v_ticket;
    if v_ticket is not null and v_ticket > 0 and v_base_faixas = 'percentual_referencia' and v_referencia > 0 then
      v_ticket_comparacao := v_ticket / v_referencia * 100;
    end if;
    if v_ticket_comparacao is not null and v_ticket_comparacao > 0 then
      select faixa into v_faixa
      from jsonb_array_elements(v_faixas) as faixas(faixa)
      where v_ticket_comparacao >= (faixa->>'min')::numeric
        and (faixa->>'max' is null or v_ticket_comparacao < (faixa->>'max')::numeric)
      limit 1;
    else
      v_faixa := null;
    end if;
    if v_faixa is not null then v_multiplicador := (v_faixa->>'multiplicador')::numeric; else v_multiplicador := null; end if;

    v_xp_base_vendas := v_vendas * v_config.xp_venda_nova;
    if v_multiplicador is null then
      -- Dado de ticket ausente: mantém apenas o XP-base, sem bônus ou redutor.
      v_xp_vendas := v_xp_base_vendas;
      v_xp_bonus_ticket := 0;
    else
      v_xp_vendas := round(v_xp_base_vendas * v_multiplicador, v_config.escala_arredondamento);
      v_xp_bonus_ticket := v_xp_vendas - v_xp_base_vendas;
    end if;
    v_xp_renovacoes := round(v_renovacoes * v_config.xp_renovacao, v_config.escala_arredondamento);

    if v_config.bonus_metas_ativo then
      if v_meta_vendas > 0 and v_vendas >= v_meta_vendas then v_bonus_vendas := v_config.bonus_meta_vendas; end if;
      if v_vendedor.tipo <> 'externo' and v_meta_renovacoes > 0 and v_renovacoes >= v_meta_renovacoes then
        v_bonus_renovacoes := v_config.bonus_meta_renovacoes;
      end if;
    end if;
    v_xp_total := round(v_xp_vendas + v_xp_renovacoes + v_bonus_vendas + v_bonus_renovacoes, v_config.escala_arredondamento);

    insert into public.xp_comercial_periodos (
      carreira_pessoa_id, vendedor_id, filial_id, mes, ano, tipo, vendas_novas, renovacoes,
      ticket_medio, multiplicador_ticket, faixa_ticket_aplicada, xp_base_vendas,
      xp_vendas_novas, xp_bonus_ticket, xp_renovacoes, xp_bonus_meta_vendas,
      xp_bonus_meta_renovacoes, xp_total_periodo, campanha_id, regra_aplicada, calculado_em
    ) values (
      v_vendedor.carreira_pessoa_id, v_vendedor.id, v_vendedor.filial_id, p_mes, p_ano, v_vendedor.tipo,
      v_vendas, v_renovacoes, v_ticket, v_multiplicador, v_faixa, v_xp_base_vendas,
      v_xp_vendas, v_xp_bonus_ticket, v_xp_renovacoes, v_bonus_vendas, v_bonus_renovacoes,
      v_xp_total, v_campanha_id,
      jsonb_build_object(
        'xp_venda_nova', v_config.xp_venda_nova,
        'xp_renovacao', v_config.xp_renovacao,
        'escala_arredondamento', v_config.escala_arredondamento,
        'bonus_metas_ativo', v_config.bonus_metas_ativo,
        'bonus_meta_vendas', v_config.bonus_meta_vendas,
        'bonus_meta_renovacoes', v_config.bonus_meta_renovacoes,
        'base_faixas', v_base_faixas,
        'referencia_ticket_campanha', v_referencia
      ), now()
    )
    on conflict (carreira_pessoa_id, ano, mes) do update set
      vendedor_id = excluded.vendedor_id,
      filial_id = excluded.filial_id,
      tipo = excluded.tipo,
      vendas_novas = excluded.vendas_novas,
      renovacoes = excluded.renovacoes,
      ticket_medio = excluded.ticket_medio,
      multiplicador_ticket = excluded.multiplicador_ticket,
      faixa_ticket_aplicada = excluded.faixa_ticket_aplicada,
      xp_base_vendas = excluded.xp_base_vendas,
      xp_vendas_novas = excluded.xp_vendas_novas,
      xp_bonus_ticket = excluded.xp_bonus_ticket,
      xp_renovacoes = excluded.xp_renovacoes,
      xp_bonus_meta_vendas = excluded.xp_bonus_meta_vendas,
      xp_bonus_meta_renovacoes = excluded.xp_bonus_meta_renovacoes,
      xp_total_periodo = excluded.xp_total_periodo,
      campanha_id = excluded.campanha_id,
      regra_aplicada = excluded.regra_aplicada,
      calculado_em = now()
    where public.xp_comercial_periodos.status = 'provisorio'
      and (
        public.xp_comercial_periodos.vendedor_id,
        public.xp_comercial_periodos.filial_id,
        public.xp_comercial_periodos.tipo,
        public.xp_comercial_periodos.vendas_novas,
        public.xp_comercial_periodos.renovacoes,
        public.xp_comercial_periodos.ticket_medio,
        public.xp_comercial_periodos.multiplicador_ticket,
        public.xp_comercial_periodos.faixa_ticket_aplicada,
        public.xp_comercial_periodos.xp_base_vendas,
        public.xp_comercial_periodos.xp_vendas_novas,
        public.xp_comercial_periodos.xp_bonus_ticket,
        public.xp_comercial_periodos.xp_renovacoes,
        public.xp_comercial_periodos.xp_bonus_meta_vendas,
        public.xp_comercial_periodos.xp_bonus_meta_renovacoes,
        public.xp_comercial_periodos.xp_total_periodo,
        public.xp_comercial_periodos.campanha_id,
        public.xp_comercial_periodos.regra_aplicada
      ) is distinct from (
        excluded.vendedor_id, excluded.filial_id, excluded.tipo, excluded.vendas_novas, excluded.renovacoes,
        excluded.ticket_medio, excluded.multiplicador_ticket, excluded.faixa_ticket_aplicada, excluded.xp_base_vendas,
        excluded.xp_vendas_novas, excluded.xp_bonus_ticket, excluded.xp_renovacoes, excluded.xp_bonus_meta_vendas,
        excluded.xp_bonus_meta_renovacoes, excluded.xp_total_periodo, excluded.campanha_id, excluded.regra_aplicada
      );
  end if;

  select * into v_periodo from public.xp_comercial_periodos p
  where p.carreira_pessoa_id = v_vendedor.carreira_pessoa_id and p.mes = p_mes and p.ano = p_ano;
  if not found then raise exception 'Não foi possível registrar o XP deste período.'; end if;

  return query select v_periodo.carreira_pessoa_id, v_periodo.vendedor_id, v_periodo.mes, v_periodo.ano,
    v_periodo.tipo, v_periodo.status, v_periodo.vendas_novas, v_periodo.renovacoes,
    v_periodo.ticket_medio, v_periodo.multiplicador_ticket, v_periodo.xp_base_vendas,
    v_periodo.xp_vendas_novas, v_periodo.xp_bonus_ticket, v_periodo.xp_renovacoes,
    v_periodo.xp_bonus_meta_vendas, v_periodo.xp_bonus_meta_renovacoes, v_periodo.xp_total_periodo,
    (select coalesce(sum(p.xp_total_periodo), 0)::numeric from public.xp_comercial_periodos p
      where p.carreira_pessoa_id = v_periodo.carreira_pessoa_id),
    v_config.bonus_metas_ativo, v_periodo.faixa_ticket_aplicada, v_periodo.campanha_id, v_periodo.calculado_em;
end;
$function$;

create or replace function public.consolidar_xp_comercial_filial(p_filial_id bigint, p_mes integer, p_ano integer)
returns integer language plpgsql security definer set search_path = '' as $function$
declare
  v_inicio date;
  v_liberacao date;
  v_vendedor record;
  v_fechados integer := 0;
begin
  if auth.uid() is null or not private.admin_tem_acesso_filial(p_filial_id) then
    raise exception 'Sem permissão para consolidar XP desta filial.' using errcode = '42501';
  end if;
  if p_mes < 1 or p_mes > 12 or p_ano < 2000 or p_ano > 2200 then
    raise exception 'Mês ou ano inválido.' using errcode = '22023';
  end if;
  v_inicio := make_date(p_ano, p_mes, 1);
  v_liberacao := (v_inicio + interval '1 month' + interval '7 days')::date;
  if v_inicio >= date_trunc('month', timezone('America/Manaus', now()))::date
     or timezone('America/Manaus', now())::date < v_liberacao then
    raise exception 'Consolide o XP depois do fechamento mensal e da primeira semana do mês seguinte.' using errcode = '22023';
  end if;
  for v_vendedor in
    select min(v.id) as vendedor_id from public.vendedores v
    where v.filial_id = p_filial_id and v.carreira_pessoa_id is not null
      and (v.ativo is true
        or exists (
          select 1 from public.vendas_admin sa
          where sa.vendedor_id = v.id
            and sa.data_venda >= v_inicio
            and sa.data_venda < (v_inicio + interval '1 month')
        )
        or exists (
          select 1 from public.renovacoes_mensais rm
          where rm.vendedor_id = v.id and rm.filial_id = v.filial_id
            and rm.mes = p_mes and rm.ano = p_ano
        ))
    group by v.carreira_pessoa_id
  loop
    perform * from public.calcular_xp_comercial_vendedor(v_vendedor.vendedor_id, p_mes, p_ano);
    update public.xp_comercial_periodos p
      set status = 'fechado', fechado_em = coalesce(p.fechado_em, now()), fechado_por = coalesce(p.fechado_por, auth.uid())
      where p.carreira_pessoa_id = (select v.carreira_pessoa_id from public.vendedores v where v.id = v_vendedor.vendedor_id)
        and p.mes = p_mes and p.ano = p_ano and p.status <> 'fechado';
    v_fechados := v_fechados + 1;
  end loop;
  return v_fechados;
end;
$function$;

create or replace function public.corrigir_xp_comercial_fechado(
  p_vendedor_id bigint, p_mes integer, p_ano integer, p_motivo text
)
returns table (xp_total_periodo numeric, xp_acumulado_carreira numeric)
language plpgsql security definer set search_path = '' as $function$
declare
  v_vendedor public.vendedores%rowtype;
  v_resultado record;
begin
  if auth.uid() is null or not private.admin_e_superadmin() then
    raise exception 'Somente o superadministrador pode corrigir XP de mês fechado.' using errcode = '42501';
  end if;
  if nullif(trim(p_motivo), '') is null then raise exception 'Informe o motivo da correção.' using errcode = '22023'; end if;
  select * into v_vendedor from public.vendedores where id = p_vendedor_id;
  if not found or not private.admin_tem_acesso_filial(v_vendedor.filial_id) then
    raise exception 'Vendedor não encontrado ou sem acesso à filial.' using errcode = '42501';
  end if;
  perform set_config('app.xp_comercial_motivo_correcao', trim(p_motivo), true);
  update public.xp_comercial_periodos p set status = 'provisorio'
    where p.carreira_pessoa_id = v_vendedor.carreira_pessoa_id and p.mes = p_mes and p.ano = p_ano and p.status = 'fechado';
  if not found then raise exception 'Não há um período fechado de XP para corrigir.' using errcode = '22023'; end if;
  select * into v_resultado from public.calcular_xp_comercial_vendedor(p_vendedor_id, p_mes, p_ano);
  update public.xp_comercial_periodos p set status = 'fechado', fechado_em = now(), fechado_por = auth.uid()
    where p.carreira_pessoa_id = v_vendedor.carreira_pessoa_id and p.mes = p_mes and p.ano = p_ano;
  return query select v_resultado.xp_total_periodo, v_resultado.xp_acumulado_carreira;
end;
$function$;

