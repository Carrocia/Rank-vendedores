-- Confere vendas cadastradas no site contra a lista completa de contratos
-- ativos exportada do IXC. Itens ausentes ficam pendentes até revisão manual.
-- Execute no SQL Editor do Supabase antes de usar a conferência no painel.

begin;

create table if not exists public.vendas_conferencia_ixc (
  id bigint generated by default as identity primary key,
  venda_id bigint not null unique,
  filial_id bigint not null references public.filiais(id) on delete restrict,
  numero_venda text not null,
  situacao text not null default 'pendente'
    check (situacao in ('pendente', 'regularizada', 'validada', 'vinculada', 'cancelada')),
  motivo text not null default 'Contrato não encontrado na lista de contratos ativos do IXC.',
  relatorio_em timestamptz not null default now(),
  criado_em timestamptz not null default now(),
  resolvido_em timestamptz,
  resolvido_por uuid,
  venda_arquivada jsonb,
  adicionais_arquivados jsonb not null default '[]'::jsonb
);

create index if not exists vendas_conferencia_ixc_pendentes_idx
  on public.vendas_conferencia_ixc (filial_id, relatorio_em desc)
  where situacao = 'pendente';

alter table public.vendas_conferencia_ixc enable row level security;
drop policy if exists vendas_conferencia_ixc_select on public.vendas_conferencia_ixc;
create policy vendas_conferencia_ixc_select on public.vendas_conferencia_ixc
  for select to authenticated
  using (private.admin_tem_acesso_filial(filial_id));

revoke all on table public.vendas_conferencia_ixc from anon, authenticated;
grant select on table public.vendas_conferencia_ixc to authenticated;

create or replace function public.conferir_vendas_ausentes_ixc(
  p_filial_ids bigint[],
  p_contratos_ativos text[]
)
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_filiais bigint[];
  v_contratos text[];
  v_afetadas integer := 0;
  v_revisoes_zero integer := 0;
begin
  if auth.uid() is null then
    raise exception 'É necessário entrar no painel administrativo.';
  end if;

  select coalesce(array_agg(distinct x), array[]::bigint[])
    into v_filiais
  from unnest(coalesce(p_filial_ids, array[]::bigint[])) x
  where x is not null;

  select coalesce(array_agg(distinct btrim(x)), array[]::text[])
    into v_contratos
  from unnest(coalesce(p_contratos_ativos, array[]::text[])) x
  where nullif(btrim(x), '') is not null;

  if cardinality(v_filiais) = 0 or cardinality(v_contratos) = 0 then
    raise exception 'O relatório precisa conter filial reconhecida e contratos ativos.';
  end if;

  if exists (
    select 1 from unnest(v_filiais) f
    where not private.admin_tem_acesso_filial(f)
  ) then
    raise exception 'Sua conta não tem acesso a todas as filiais deste relatório.';
  end if;

  -- Se uma venda pendente reaparecer como ativa, retira-a da fila sem apagar
  -- a decisão ou o histórico das demais situações.
  update public.vendas_conferencia_ixc c
  set situacao = 'regularizada',
      resolvido_em = now(),
      resolvido_por = auth.uid(),
      relatorio_em = now()
  from public.vendas v
  where c.venda_id = v.id
    and c.situacao = 'pendente'
    and c.motivo <> 'revisar_valor_variavel_ixc'
    and v.filial_destino_id = any(v_filiais)
    and btrim(coalesce(v.numero_venda, '')) = any(v_contratos);

  -- Vendas antigas com valor de plano zero não tinham pendência própria.
  -- Coloca-as na fila de revisão, mesmo se o contrato estiver ativo no IXC.
  insert into public.vendas_conferencia_ixc
    (venda_id, filial_id, numero_venda, situacao, motivo, relatorio_em)
  select v.id, v.filial_destino_id, btrim(v.numero_venda), 'pendente',
         'revisar_valor_zero_legado', now()
  from public.vendas v
  where v.filial_destino_id = any(v_filiais)
    and coalesce(v.valor, 0) = 0
    and nullif(btrim(coalesce(v.numero_venda, '')), '') is not null
  on conflict (venda_id) do update
    set situacao = 'pendente',
        numero_venda = excluded.numero_venda,
        relatorio_em = now(),
        motivo = 'revisar_valor_zero_legado'
    where public.vendas_conferencia_ixc.situacao in ('pendente', 'regularizada')
      and public.vendas_conferencia_ixc.motivo <> 'revisar_valor_variavel_ixc';
  get diagnostics v_revisoes_zero = row_count;

  insert into public.vendas_conferencia_ixc
    (venda_id, filial_id, numero_venda, situacao, relatorio_em)
  select v.id, v.filial_destino_id, btrim(v.numero_venda), 'pendente', now()
  from public.vendas v
  where v.filial_destino_id = any(v_filiais)
    and nullif(btrim(v.numero_venda), '') is not null
    and coalesce(v.valor, 0) <> 0
    and not (btrim(v.numero_venda) = any(v_contratos))
  on conflict (venda_id) do update
    set situacao = 'pendente',
        numero_venda = excluded.numero_venda,
        relatorio_em = now(),
        motivo = 'Contrato não encontrado na lista de contratos ativos do IXC.'
    where public.vendas_conferencia_ixc.situacao in ('pendente', 'regularizada')
      and public.vendas_conferencia_ixc.motivo <> 'revisar_valor_variavel_ixc';

  get diagnostics v_afetadas = row_count;
  return v_afetadas + v_revisoes_zero;
end;
$function$;

create or replace function public.resolver_conferencia_venda_ixc(
  p_pendencia_id bigint,
  p_decisao text,
  p_numero_contrato text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_pendencia public.vendas_conferencia_ixc%rowtype;
  v_venda public.vendas%rowtype;
  v_adicionais jsonb;
  v_numero text := nullif(btrim(coalesce(p_numero_contrato, '')), '');
begin
  if auth.uid() is null then
    raise exception 'É necessário entrar no painel administrativo.';
  end if;

  select * into v_pendencia
  from public.vendas_conferencia_ixc
  where id = p_pendencia_id
  for update;

  if not found then raise exception 'Pendência não encontrada.'; end if;
  if not private.admin_tem_acesso_filial(v_pendencia.filial_id) then
    raise exception 'Sua conta não tem acesso a esta filial.';
  end if;
  if v_pendencia.situacao <> 'pendente' then
    raise exception 'Esta pendência já foi resolvida ou regularizada.';
  end if;

  select * into v_venda
  from public.vendas
  where id = v_pendencia.venda_id
  for update;

  if not found then raise exception 'A venda original não foi encontrada.'; end if;

  if p_decisao = 'validar' then
    update public.vendas_conferencia_ixc
    set situacao = 'validada', resolvido_em = now(), resolvido_por = auth.uid()
    where id = p_pendencia_id;
    return;
  end if;

  if p_decisao = 'cancelar' then
    select coalesce(jsonb_agg(to_jsonb(a)), '[]'::jsonb)
      into v_adicionais
    from public.venda_adicionais a
    where a.venda_id = v_venda.id;

    update public.vendas_conferencia_ixc
    set situacao = 'cancelada',
        resolvido_em = now(),
        resolvido_por = auth.uid(),
        venda_arquivada = to_jsonb(v_venda),
        adicionais_arquivados = v_adicionais
    where id = p_pendencia_id;

    delete from public.venda_adicionais where venda_id = v_venda.id;
    delete from public.vendas where id = v_venda.id;
    return;
  end if;

  if p_decisao = 'vincular' then
    if v_numero is null or v_numero !~ '^\d+$' then
      raise exception 'Informe um número de contrato IXC válido.';
    end if;
    if exists (
      select 1 from public.vendas v
      where btrim(coalesce(v.numero_venda, '')) = v_numero
        and v.id <> v_venda.id
    ) then
      raise exception 'Esse contrato já está vinculado a outra venda.';
    end if;
    update public.vendas set numero_venda = v_numero where id = v_venda.id;
    update public.vendas_conferencia_ixc
    set situacao = 'vinculada', numero_venda = v_numero,
        resolvido_em = now(), resolvido_por = auth.uid()
    where id = p_pendencia_id;
    return;
  end if;

  raise exception 'Decisão inválida.';
end;
$function$;

revoke all on function public.conferir_vendas_ausentes_ixc(bigint[], text[]) from public, anon;
revoke all on function public.resolver_conferencia_venda_ixc(bigint, text, text) from public, anon;
grant execute on function public.conferir_vendas_ausentes_ixc(bigint[], text[]) to authenticated;
grant execute on function public.resolver_conferencia_venda_ixc(bigint, text, text) to authenticated;

commit;
